// Writes `lib/not-a-face-prints.ts` from the kart fixtures.
//
// The committed Not-a-Face Prints are a copy of the prints for the detections
// `fixtures/karts/expected.json` marks `reference: true`, and 512 floats are
// not a thing to keep by hand. This is how they are regenerated when the
// fixture prints move — which is what the re-calibration ticket does, and what
// growing the reference set will do.
//
//   pnpm --filter @meco/identify generate:not-a-face-prints
//
// `expected.json` is the ground truth and `face-prints.json` merely copies its
// classification, so the two are cross-checked here: marking a detection
// `reference: true` in one file alone fails loudly instead of committing
// nothing. `tests/calibration.test.ts` then asserts the committed file still
// equals the fixtures, so forgetting to run this fails the gate rather than
// shipping a stale reference.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const KARTS = fileURLToPath(
  new URL("../../../fixtures/karts/", import.meta.url)
);
const OUT = fileURLToPath(
  new URL("../lib/not-a-face-prints.ts", import.meta.url)
);

/** `PRINT_DIMENSIONS` in `lib/constants.ts`, which this script cannot import. */
const PRINT_DIMENSIONS = 512;

/** `PRINT_MODEL` in `lib/constants.ts`, for the same reason. */
const PRINT_MODEL = { name: "edgeface", version: "1" };

const read = (name) => JSON.parse(readFileSync(`${KARTS}${name}`, "utf8"));

const printed = read("face-prints.json");
const expected = read("expected.json");

// The dump says which Model took these prints. A print from any other Model is
// an Uncompared Face to identify, so committing one as a Not-a-Face Print
// would compare two unrelated networks term by term and could refuse a real
// face on nothing. Refused here, at the one place the vectors leave the
// fixtures: re-print with `pnpm --filter @meco/models print:fixtures` first.
const model = printed.printedBy?.model;
if (model?.name !== PRINT_MODEL.name || model.version !== PRINT_MODEL.version) {
  throw new Error(
    `fixtures/karts/face-prints.json was printed by ${
      model === undefined
        ? "no recorded Model"
        : `${model.name}/${model.version}`
    }, and the Print Model is ${PRINT_MODEL.name}/${PRINT_MODEL.version}`
  );
}

/**
 * Every detection the human marked `reference: true`, in detection order,
 * joined onto the print the dump took of it.
 */
const reference = expected.images.flatMap((image) =>
  image.faces.flatMap((face, index) => {
    if (face.reference !== true) return [];
    const id = `${image.file}#${index}`;
    if (face.is !== "not-a-face") {
      throw new Error(`${id} is marked reference and "${face.is}"`);
    }
    const print = printed.prints.find(
      (one) => one.file === image.file && one.index === index
    );
    if (print === undefined) {
      throw new Error(`${id} is marked reference and has no print`);
    }
    if (print.label !== face.label || print.is !== face.is) {
      throw new Error(
        `${id} is classified differently in the two fixture files`
      );
    }
    if (print.print.length !== PRINT_DIMENSIONS) {
      throw new Error(`${id} is not ${PRINT_DIMENSIONS} floats`);
    }
    return [{ id, saw: face.label, vector: print.print }];
  })
);

if (reference.length === 0) {
  throw new Error("fixtures/karts/expected.json marks no reference detection");
}

const entries = reference
  .map(
    (one) => `  {
    id: ${JSON.stringify(one.id)},
    saw: ${JSON.stringify(one.saw)},
    vector: [${one.vector.map((value) => JSON.stringify(value)).join(", ")}],
  },`
  )
  .join("\n");

const source = `/**
 * The Face Prints of things that are not faces.
 *
 * Generated by \`scripts/generate-not-a-face-prints.mjs\` from the detections
 * \`fixtures/karts/expected.json\` marks \`reference: true\`, whose prints are in
 * \`fixtures/karts/face-prints.json\`. Do not edit by hand: run
 * \`pnpm --filter @meco/identify generate:not-a-face-prints\`.
 *
 * They are committed in code and never a records row, because they are a fact
 * about a Model and not about a person or a Brand. A Face Print at or above
 * \`NOT_A_FACE_THRESHOLD\` to one of them carries no identity, at match time and
 * at enrolment alike (ADR-0003, amendment; ADR-0012, Decision 3).
 *
 * Growing the set needs a CC0 or public-domain photograph
 * (\`fixtures/karts/LICENCE.md\`) and a re-run of the Not-a-Face sweep in
 * \`tests/calibration.test.ts\`: the threshold refuses one real face already and
 * has no room below it.
 */

/** One committed print of something a human confirmed is not a face. */
export interface NotAFacePrint {
  /** \`<file>#<index>\` in \`fixtures/karts/\`, so a refusal can name it. */
  readonly id: string;
  /** What the human saw in the box, cut out at 2.2x its own size. */
  readonly saw: string;
  /** The print itself, from the Print Model, on the unit sphere. */
  readonly vector: readonly number[];
}

export const NOT_A_FACE_PRINTS: readonly NotAFacePrint[] = [
${entries}
];
`;

writeFileSync(OUT, await format(source, { filepath: OUT }));

console.log(
  `wrote ${reference.length} Not-a-Face Print(s) to lib/not-a-face-prints.ts: ${reference
    .map((one) => one.id)
    .join(", ")}`
);
